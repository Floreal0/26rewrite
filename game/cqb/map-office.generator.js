/* CQB 主地图「办公楼·扩建版」生成器 v2 —— 56×40 格
 *
 * 结构:原 40×26 核心区原样保留;
 *   南延:西/东走廊 + 大厅南延接「大会议室」+ 西南楼梯间 + 东南开放办公区
 *   东扩:「北/南档案室」双联房,经右上房、右下房的东墙进入
 * 输出:map-office.json(rooms / doors / crates / spawns)
 */
const fs = require("fs");

const W = 56, H = 40;
const g = Array.from({ length: H }, () => Array(W).fill("#"));

// ---------- 房间地板 ----------
const rooms = [
  ["TL 左上房",     1,  1,  8,  8],
  ["LS 西储物间",   1, 10,  8,  6],
  ["BL 西楼梯间北", 1, 17,  8,  8],
  ["SW 西楼梯间南", 1, 27,  8, 12],
  ["西走廊",       10,  1,  4, 38],
  ["中央大厅",     15,  1, 10, 31],
  ["大会议室",     15, 33, 10,  6],
  ["东走廊",       26,  1,  4, 38],
  ["TR 右上房",    31,  1,  8,  8],
  ["MR 东储物间",  31, 10,  8,  6],
  ["BR 右楼梯间北",31, 17,  8,  8],
  ["开放办公区",   31, 27, 24, 12],
  ["北档案室",     40,  3, 15,  9],
  ["南档案室",     40, 13, 15, 10],
];
for (const [, x, y, w, h] of rooms)
  for (let j = y; j < y + h; j++)
    for (let i = x; i < x + w; i++) g[j][i] = ".";

// ---------- 门洞(左右错位原则,杜绝横穿狙击道) ----------
const doors = [
  // ---- 原核心区 ----
  [9, 3], [9, 4],       // TL -> 西走廊
  [9, 11], [9, 12],     // LS -> 西走廊
  [9, 18], [9, 19],     // BL -> 西走廊
  [14, 5], [14, 6],     // 西走廊 -> 大厅 北口
  [14, 16], [14, 17],   // 西走廊 -> 大厅 南口
  [14, 10], [14, 11],   // LS -> 大厅 捷径
  [25, 5], [25, 6],     // 大厅 -> 东走廊 北口
  [25, 18], [25, 19],   // 大厅 -> 东走廊 南口
  [25, 13], [25, 14],   // MR -> 大厅 捷径
  [30, 3], [30, 4],     // TR -> 东走廊
  [30, 11], [30, 12],   // MR -> 东走廊
  [30, 18], [30, 19],   // BR -> 东走廊
  // ---- 南延新区 ----
  [9, 29], [9, 30],     // SW -> 西走廊
  [9, 35], [9, 36],     // SW -> 西走廊 第二入口
  [19, 32], [20, 32],   // 大厅 -> 大会议室(双开门)
  [30, 29], [30, 30],   // 开放办公区 -> 东走廊
  // ---- 东扩新区 ----
  [39, 5], [39, 6],     // TR -> 北档案室
  [39, 18], [39, 19],   // BR -> 南档案室
  [47, 12],             // 北档案室 <-> 南档案室 竖向连接
];
for (const [x, y] of doors) g[y][x] = "D";

// ---------- 掩体箱 ----------
const crates = [
  // 原核心区
  [17, 5], [22, 8], [16, 13], [21, 16], [18, 21], [19, 11],
  [4, 4], [35, 4], [4, 20], [35, 20],
  // 南延
  [20, 28],                    // 大厅南段
  [17, 34], [22, 36],          // 大会议室立柱
  [4, 30], [6, 35],            // 西楼梯间
  [34, 30], [40, 33], [46, 29], [50, 35], [43, 37], // 开放办公区立柱群
  // 东扩
  [45, 6], [51, 9],            // 北档案室
  [44, 16], [51, 19],          // 南档案室
];
for (const [x, y] of crates) g[y][x] = "C";

// ---------- 出生点(共 10 个,覆盖全部区域,开局朝墙) ----------
const spawns = [
  [2, 2], [37, 2], [2, 23], [37, 23],      // 四角房
  [11, 12], [28, 12],                      // 西/东走廊中段
  [19, 36],                                // 大会议室
  [4, 32],                                 // 西楼梯间南
  [47, 32],                                // 开放办公区
  [47, 7],                                 // 北档案室
];
spawns.forEach(([x, y], i) => (g[y][x] = String(i + 1)));

// ---------- 校验与导出 ----------
let errors = [];
for (const [x, y] of [...doors, ...crates, ...spawns]) {
  if (x <= 0 || y <= 0 || x >= W - 1 || y >= H - 1)
    errors.push(`越界: (${x},${y})`);
}
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

fs.writeFileSync(
  __dirname + "/map-office.json",
  JSON.stringify({
    name: "办公楼·扩建版", w: W, h: H,
    cell: 32, visionR: 12,
    rooms, doors, crates, spawns,
  }, null, 2));

console.log(`办公楼·扩建版: ${W}x${H} 格`);
console.log(`房间 ${rooms.length} | 门洞 ${doors.length} | 掩体 ${crates.length} | 出生点 ${spawns.length}`);
console.log("map-office.json 已导出");
